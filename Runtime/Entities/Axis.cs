namespace Emas
{
    /// <summary>
    /// Identifies a signed source axis used by a coordinate-system mapping.
    /// </summary>
    public enum Axis
    {
        /// <summary>The source's positive X axis.</summary>
        PositiveX = 1,
        /// <summary>The source's negative X axis.</summary>
        NegativeX = -1,
        /// <summary>The source's positive Y axis.</summary>
        PositiveY = 2,
        /// <summary>The source's negative Y axis.</summary>
        NegativeY = -2,
        /// <summary>The source's positive Z axis.</summary>
        PositiveZ = 3,
        /// <summary>The source's negative Z axis.</summary>
        NegativeZ = -3
    }
}
